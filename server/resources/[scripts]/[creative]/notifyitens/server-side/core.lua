-----------------------------------------------------------------------------------------------------------------------------------------
-- VRP
-----------------------------------------------------------------------------------------------------------------------------------------
local Tunnel = module("vrp","lib/Tunnel")
local Proxy = module("vrp","lib/Proxy")
vRPC = Tunnel.getInterface("vRP")
vRP = Proxy.getInterface("vRP")
-----------------------------------------------------------------------------------------------------------------------------------------
-- CONNECTION
-----------------------------------------------------------------------------------------------------------------------------------------
Creative = {}
Tunnel.bindInterface("notifyitens",Creative)
vCLIENT = Tunnel.getInterface("notifyitens")
-----------------------------------------------------------------------------------------------------------------------------------------
-- EXPORTS
-----------------------------------------------------------------------------------------------------------------------------------------
exports("NotifyItens",function(source,mode,item,amount,name)
	TriggerClientEvent("itensNotify",source,{ mode,item,amount,name })
end)

-----------------------------------------------------------------------------------------------------------------------------------------
-- NOTIFYITENS:SEND
-----------------------------------------------------------------------------------------------------------------------------------------
RegisterServerEvent("notifyitens:send")
AddEventHandler("notifyitens:send",function(source,status)
	TriggerClientEvent("itensNotify",source,status)
end)
