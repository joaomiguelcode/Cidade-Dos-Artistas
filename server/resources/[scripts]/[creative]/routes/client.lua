local processedTable = {}
Citizen.CreateThread(function()
	for routeCode, route in pairs(routes) do
		for k, v in pairs(route.startPoints) do
			table.insert(processedTable,{ x = v["x"], y = v["y"], z = v["z"], routeCode = routeCode })
		end
	end
end)
-------------------------------------------------------------------------------------------------
--[ AÇÃO ]---------------------------------------------------------------------------------------
-------------------------------------------------------------------------------------------------
Citizen.CreateThread(function()
	Wait(1500)
	while true do
		local msec = 500
		for k, v in pairs(processedTable) do
			local ped = PlayerPedId()
			local coords = GetEntityCoords(ped)
			local distance = #(coords - vec3(v["x"], v["y"], v["z"]))
			if distance <= 5.0 then
				msec = 4
				if distance <= 1.5 then
					DrawText3D(v["x"], v["y"], v["z"], "~p~E~w~   ABRIR")
					if IsControlJustPressed(0,38) then
						if vSERVER.checkPermission(v["routeCode"]) then
							currentRoute = v["routeCode"]
							ToggleActionMenu()
						end
					end
				end
			end
		end
        
		Citizen.Wait(msec)
	end
end)

Citizen.CreateThread(function()
	while true do
		local AE = 500
		if currentRoute then
			local ped = PlayerPedId()
			local pcoords = GetEntityCoords(ped)
			local distance = #(vec3(routesPath[currentRoute][currentPathPosition].x,routesPath[currentRoute][currentPathPosition].y,routesPath[currentRoute][currentPathPosition].z) - pcoords)
			AE = 4
			if distance <= 1.5 then
				DrawText3D(routesPath[currentRoute][currentPathPosition].x,routesPath[currentRoute][currentPathPosition].y,routesPath[currentRoute][currentPathPosition].z, "~p~E~w~   COLETAR")
				
				if not IsPedInAnyVehicle(ped) then
					if IsControlJustPressed(0,38) then
						vSERVER.checkPayment(currentRoute, position)
												
						RemoveBlip(currentBlip)
						currentPathPosition = currentPathPosition + 1
						if currentPathPosition > #routesPath[currentRoute] then
							currentPathPosition = 1
						end

						createBlip(routes[currentRoute].title, routesPath[currentRoute][currentPathPosition])
					end
				end
			end
		end

		Citizen.Wait(AE)
	end
end)

Citizen.CreateThread(function()
	while true do
		local sleep = 1000
		if currentRoute then
			sleep = 4
			if IsControlJustPressed(0, 168) then
				currentRoute = nil
				currentPathPosition = 1
				RemoveBlip(currentBlip)
				TriggerServerEvent("routes:endRoute")
				TriggerEvent("Notify","default","Rota encerrada",10000)
			end
		end
		Wait(sleep)
	end
end)
