-- NUIMESSAGE
-----------------------------------------------------------------------------------------------------------------------------------------
function openNui(Garage)
	Opened = not Opened
	if Opened then
		GarageOpen = Garage
		SetNuiFocus(true,true)
		openPublicGarage()
	else
		SetNuiFocus(false,false)
		CloseGarage()
	end
end

function CloseGarage()
	SetNuiFocus(false,false)
	SendNUIMessage({action = "hide"})
	Opened = false
end

RegisterNetEvent("epic_garages:Close",CloseGarage)

function openPublicGarage()
	SendNUIMessage({ action = "show", serv = false })
	Opened = true
	CreateThread(function()
		while Opened do
			local Coords = vec3(Garages[GarageOpen].x,Garages[GarageOpen].y,Garages[GarageOpen].z)
			local Distance = #(Coords - GetEntityCoords(PlayerPedId()))
			if Distance > 5 then
				SetNuiFocus(false,false)
				CloseGarage()
			end
			Wait(1000)
		end
	end)
end
